"""Read-only presentation content and provenance audit.

This checks slide structure, notes, ordinary production metadata, and obvious
draft residue. It does not claim to detect whether prose was written by AI.
"""
from collections import Counter
from pathlib import Path
import re
from pptx import Presentation

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "slides" / "lecture_when_can_we_trust_clinical_ai.pptx"

def audit(path: Path = TARGET):
    pres = Presentation(path)
    assert len(pres.slides) == 23, f"Expected 23 integrated lecture slides, got {len(pres.slides)}"
    slides = []
    minimum_font_sizes = []
    science_refs = 0
    for num, slide in enumerate(pres.slides, 1):
        pieces = []
        for sh in slide.shapes:
            if sh.has_text_frame:
                pieces.append(sh.text_frame.text)
                for para in sh.text_frame.paragraphs:
                    for run in para.runs:
                        if run.font.size is not None:
                            minimum_font_sizes.append((run.font.size.pt, num, run.text[:60]))
            if sh.has_table:
                pieces.extend(cell.text for row in sh.table.rows for cell in row.cells)
        text = "\n".join(pieces)
        if not text.strip():
            raise AssertionError(f"Slide {num} has no readable text")
        notes = slide.notes_slide.notes_text_frame.text
        if len(notes.strip()) < 80:
            raise AssertionError(f"Slide {num} has missing or very short speaking notes")
        science_refs += int("[Sources]" in notes)
        if "generated by chatgpt" in (text + notes).lower() or "generated by claude" in (text + notes).lower():
            raise AssertionError(f"Slide {num} contains accidental drafting attribution")
        if ";" in text:
            raise AssertionError(f"Slide {num} contains a semicolon in visible slide prose")
        # Narrative notes must use periods rather than prose semicolons;
        # metadata/citation fields can include semicolons, but none should here.
        if ";" in notes:
            print(f"CHECK NOTE SEMICOLON slide {num}: inspect context manually")
        slides.append((num, len(text.split()), text.splitlines()[0][:90]))
    print(f"Presentation: {path.name}")
    print(f"Slides: {len(slides)}; note source blocks: {science_refs}")
    print(f"Metadata author: {pres.core_properties.author!r}")
    print(f"Metadata modified by: {pres.core_properties.last_modified_by!r}")
    print(f"Metadata title: {pres.core_properties.title!r}")
    if minimum_font_sizes:
        smallest = sorted(minimum_font_sizes)[:8]
        print("Smallest slide text runs (pt, slide, excerpt):", smallest)
        if min(x[0] for x in smallest) < 10:
            raise AssertionError("Slide content below 10pt requires manual correction")
    for idx, count, title in slides:
        print(f"Slide {idx:02d}: {count:3d} words; first text: {title}")
        if count > 115:
            print(f"REVIEW SLIDE {idx}: high visible word count")
    assert science_refs >= 5, "Add citations for key methodological slides"
    return slides

if __name__ == "__main__":
    audit()
